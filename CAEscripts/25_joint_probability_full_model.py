# =============================================================================
ALPHA    = 1.0 / 137.035999177      # безразмерная постоянная связи (канон)
ALPHA_MZ = 1.0 / 127.95             # бегущая alpha на масштабе M_Z (только для G_F)
M_E      = 0.51099895               # МэВ, масса электрона (калибровочный эталон)
M_MU_EXP = 105.6583755              # МэВ, масса мюона (для a_mu^HVP)
HC       = 197.3269804              # МэВ*фм, hbar*c
PI       = math.pi

# =============================================================================
# БАЗОВЫЕ ВЕЛИЧИНЫ (не зависят от (p,q))
# =============================================================================
E_0    = M_E / ALPHA                          # квант массы Намбу, МэВ
M_PI   = 2.0 * E_0                            # заряженный пион, МэВ
C_BASE = (13.4/13.0) * (M_E/ALPHA) * (1.0 - (4.0/3.0)*ALPHA**2)  # базовый квант на единицу S=p^2+q^2

# =============================================================================
# ОБОБЩЕННЫЕ ФОРМУЛЫ, ЗАВИСЯЩИЕ ОТ (p,q)  [естественное продолжение формул манифеста]
# =============================================================================
def M_p(p, q):
    """M_p = (p^2+q^2) * C_BASE ; 13 = 3^2+2^2."""
    return (p*p + q*q) * C_BASE

def M_n(p, q):
    """M_n = M_p * (1 + (3/16)*alpha*(1+alpha/pi))."""
    return M_p(p, q) * (1.0 + (3.0/16.0)*ALPHA*(1.0 + ALPHA/PI))

def dM_np(p, q):
    """Delta M_np = (3/16)*alpha*M_p*(1+alpha/pi)."""
    return M_p(p, q) * (3.0/16.0)*ALPHA*(1.0 + ALPHA/PI)

def r_c(p, q):
    """Зарядовый радиус r_c = 4*hbar*c/M_p (фм)."""
    return 4.0*HC/M_p(p, q)

def R_m(p, q):
    """Массовый радиус R_m = 3*hbar*c/M_p (фм)."""
    return 3.0*HC/M_p(p, q)

def f_ratio(p, q):
    """Форм-фактор f = R_m/r_c = p/(2q)."""
    return p/(2.0*q)

def Lambda0(p, q):
    """Гиперон Lambda^0 = M_p + (5/3)*m_mu (МэВ)."""
    return M_p(p, q) + (5.0/3.0)*M_MU_EXP

def sin2W(p, q):
    """Угол Вайнберга sin^2(theta_W) = p/(p^2+q^2)."""
    return p/(p*p + q*q)

def theta0(p, q):
    """Угол Лоде theta_0 = q/p^2 (рад)."""
    return q/(p*p)

def M_W(p, q):
    """M_W = (M_p/alpha)*sqrt((q^2+1)/(p^2+q^2))*(1+7*alpha/(2*pi)) (МэВ). 5=q^2+1, 13=p^2+q^2."""
    S = p*p + q*q
    return (M_p(p, q)/ALPHA) * math.sqrt((q*q + 1.0)/S) * (1.0 + 7.0*ALPHA/(2.0*PI))

def M_Z(p, q):
    """M_Z = (M_p/alpha/sqrt(2))*(1+(5/4)*alpha/pi) (МэВ).
    ИСПРАВЛЕНО: (5/4)·α/π — дедуктивный погранслой нейтрального канала
    (манифест L1011-1013), БЕЗ бегущей α(MZ). 5 = p+q = 3+2."""
    return (M_p(p, q)/ALPHA) * (1.0/math.sqrt(2.0)) * (1.0 + (5.0/4.0)*(ALPHA/PI))

def M_H(p, q):
    """M_H = (M_p/alpha)*(1-(3S/5)*alpha/pi) (МэВ). 39/5 = 3*13/5 -> 3S/5."""
    S = p*p + q*q
    return (M_p(p, q)/ALPHA) * (1.0 - (3.0*S/5.0)*(ALPHA/PI))

def rho_param(p, q):
    """Параметр Вельтмана rho = M_W^2/(M_Z^2*cos^2(theta_W)).
    С новым M_Z: rho = [(1+δ_W)/(1+δ_Z)]^2 = 1.010450 (манифест L1023)."""
    return M_W(p, q)**2 / (M_Z(p, q)**2 * (1.0 - sin2W(p, q)))

def G_F(p, q):
    """Константа Ферми G_F = pi*alpha(M_Z)/(sqrt(2)*M_W[GeV]^2*sin^2(theta_W)) (ГэВ^-2).
    α(MZ)=1/127.95 — внешний вход (манифест L2438)."""
    M_W_GeV = M_W(p, q)/1000.0
    return PI*ALPHA_MZ/(math.sqrt(2.0)*M_W_GeV**2*sin2W(p, q))

def E_b(p, q):
    """Энергия связи дейтрона E_b = M_pi^2/(2*M_p)*(3/14) (МэВ)."""
    return M_PI**2/(2.0*M_p(p, q))*(3.0/14.0)

def P_D(p, q):
    """Доля D-волны P_D = p/(4*(p^2+q^2))."""
    return p/(4.0*(p*p + q*q))

def M_rho(p, q):
    """Векторный мезон M_rho = (S-2)*E_0 (МэВ). 11 = 13-2 = S-2."""
    return (p*p + q*q - 2.0)*E_0

def a_mu_HVP(p, q):
    """Адронный вклад a_mu^HVP = (2/3)*(alpha/pi)^2*(m_mu/M_rho)^2*(1+delta_w)."""
    return (2.0/3.0)*(ALPHA/PI)**2 * (M_MU_EXP/M_rho(p, q))**2 * (1.0 + 0.00348424)

def _m_nu_k_eV(p, q, k):
    """Цепочка v52 (канон B10, 2026-09-05): M_nu = 2*alpha^5*(M_p/3)/(1+1/(6*pi));
    m_{nu,k} = M_nu*[1+sqrt(1.2)*cos(theta_1 + 2*pi*(k-1)/3)]^2 (эВ),
    theta_1 = pi - 2/3 - 1.5*alpha/pi = 141.6026° (манифест L1504)."""
