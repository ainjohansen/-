#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
================================================================================
ТОПОЛОГИЧЕСКАЯ ЭЛАСТОДИНАМИКА ВАКУУМА (ТЭВ)
Скрипт 23: Разность масс нейтрон–протон ΔM_np и МАССА НЕЙТРОНА M_n — v5.2
================================================================================
ИСПРАВЛЕНИЕ ПО АУДИТУ (ЧАСТЬ 3, П.4 + ЧАСТЬ 1, П.2):
  Старый код проверял только расщепление ΔM_np ≈ 1.28678 МэВ, но НЕ тестировал
  результирующую массу нейтрона M_n — из-за этого в таблицы манифеста вкралась
  опечатка «0.073%» (на два порядка хуже реальной точности).

  ФОРМУЛА ТЭВ (из тензора девиатора кольца T(3,2)):
     ΔM_np = (3/16)·α·M_p·(1 + α/π),   M_n = M_p + ΔM_np
  где M_p = 938.271740 МэВ — каноническая масса протона ТЭВ (audit v5.2).

КОНТРОЛЬНЫЕ ЗНАЧЕНИЯ (audit v5.2):
   |ΔM_np − 1.28678| < 1e-4 МэВ
   rel_err(M_n) < 1e-5  → точность ВЫШЕ 7.5 ppm, блокирует запись «0.073%»

РЕЗУЛЬТАТ (проверено прогоном):
   ΔM_np(ТЭВ) = 1.2867757 МэВ | CODATA 1.2933324 → откл. −0.507% (честно)
   M_n(ТЭВ)   = 939.5585157 МэВ | CODATA 939.56542052 → 7.35 ppm ✓ (< 1e-5)
================================================================================
"""

import math
import sympy as sp

# ==============================================================================
# [1] КОНСТАНТЫ
# ==============================================================================
ALPHA_INV = 137.035999177          # 1/α, CODATA
ALPHA     = 1.0 / ALPHA_INV
M_P_TEV   = 938.271740             # МэВ — каноническая масса протона ТЭВ (audit v5.2)
M_N_EXP   = 939.56542052           # МэВ, CODATA 2022 (эксперимент)
DM_NP_CODATA = 1.29333236          # МэВ, CODATA 2022: M_n − M_p

print("=" * 74)
print(" СКРИПТ 23: РАЗНОСТЬ МАСС НЕЙТРОН–ПРОТОН ΔM_np И МАССА NEUTRONA M_n")
print(" (v5.2, audit-versii-52.md — калибровка точности на 7.3 ppm)")
print("=" * 74)
print(f"   alpha        = {ALPHA:.12f}")
print(f"   M_p(ТЭВ)     = {M_P_TEV} МэВ")
print(f"   M_n(CODATA)  = {M_N_EXP} МэВ")
print(f"   ΔM_np(CODATA)= {DM_NP_CODATA:.8f} МэВ")
print("-" * 74)

# ==============================================================================
# [2] ФОРМУЛА ТЭВ (символьно, SymPy — без срезания углов)
# ==============================================================================
alpha_sym, Mp_sym = sp.symbols("alpha M_p", positive=True)

delta_np_sym = sp.Rational(3, 16) * alpha_sym * Mp_sym * (1 + alpha_sym / sp.pi)
Mn_sym       = Mp_sym + delta_np_sym          # полная масса нейтрона

print(f"\n[2] Символьные формулы (SymPy):")
print(f"   ΔM_np = {sp.simplify(delta_np_sym)}")
print(f"   M_n   = {sp.simplify(Mn_sym)}")

# ==============================================================================
# [3] ЧИСЛЕННЫЙ РАСЧЁТ
# ==============================================================================
delta_np_val = float(delta_np_sym.subs({alpha_sym: ALPHA, Mp_sym: M_P_TEV}))
M_n_tev      = M_P_TEV + delta_np_val

print(f"\n[3] Численный расчёт:")
print(f"   (3/16)·α·M_p       = {0.1875 * ALPHA * M_P_TEV:.8f} МэВ")
print(f"   ×(1 + α/π)         = ×{1 + ALPHA/math.pi:.8f}")
print(f"   ΔM_np(ТЭВ)         = {delta_np_val:.8f} МэВ   (audit: 1.28678)")
print(f"   M_n(ТЭВ)           = {M_n_tev:.8f} МэВ   (audit: 939.55852)")

# ==============================================================================
# [4] СРАВНЕНИЕ ΔM_np С CODATA — ЧЕСТНО
# ==============================================================================
dev_abs = delta_np_val - DM_NP_CODATA
dev_rel = dev_abs / DM_NP_CODATA * 100.0

print(f"\n[4] Сравнение ΔM_np с CODATA 2022:")
print(f"   ΔM_np(ТЭВ)    = {delta_np_val:.8f} МэВ")
print(f"   ΔM_np(CODATA) = {DM_NP_CODATA:.8f} МэВ")
print(f"   Δ             = {dev_abs:+.8f} МэВ = {dev_abs*1000:+.4f} кэВ")
print(f"   Отклонение    = {dev_rel:+.4f} %  (честно: формула не претендует на ppm)")

# ==============================================================================
# [5] МАССА НЕЙТРОНА — КЛЮЧЕВАЯ ПРОВЕРКА ТОЧНОСТИ (audit ЧАСТЬ 1, П.2)
# ==============================================================================
dev_Mn      = M_n_tev - M_N_EXP
rel_err_Mn  = abs(M_n_tev - M_N_EXP) / M_N_EXP          # относительная погрешность
ppm_Mn      = rel_err_Mn * 1e6                           # в ppm

print(f"\n[5] Масса нейтрона (ключевая проверка):")
print(f"   M_n(ТЭВ)    = M_p + ΔM_np = {M_n_tev:.8f} МэВ")
print(f"   M_n(CODATA) = {M_N_EXP:.8f} МэВ")
print(f"   Δ           = {dev_Mn:+.8f} МэВ = {dev_Mn*1000:+.4f} кэВ")
print(f"   Отклонение  = {rel_err_Mn*100:.6e} % = {ppm_Mn:.2f} ppm")
print(f"   → реальная точность модели: {ppm_Mn:.1f} ppm (НЕ «0.073%» — опечатка в таблицах)")

# Чувствительность к конвенции массы протона (прозрачность):
M_n_cod_mp = 938.27208816 + float(delta_np_sym.subs({alpha_sym: ALPHA, Mp_sym: 938.27208816}))
print(f"   [сравнение] при M_p(CODATA)=938.27208816: M_n = {M_n_cod_mp:.8f} МэВ "
      f"(Δ = {(M_n_cod_mp-M_N_EXP)*1e3:+.4f} кэВ, {abs(M_n_cod_mp-M_N_EXP)/M_N_EXP*1e6:.2f} ppm)")

# ==============================================================================
# [6] ПРОВЕРКА АЛЬТЕРНАТИВНЫХ ФОРМУЛ (реестр багов)
# ==============================================================================
print(f"\n[6] Альтернативные формулы (реестр багов):")
dm_v52 = 0.51099895 * (1 + ALPHA/math.pi * math.log(13/2) + 13.4 * ALPHA**2 / math.pi)
print(f"   v51/v52: m_e[1+α/π·ln(13/2)+13.4α²/π] = {dm_v52:.6f} МэВ  ← B1 (×2.52 занижено)")
dm_no_corr = (3/16) * ALPHA * M_P_TEV
print(f"   Без поправки: (3/16)·α·M_p             = {dm_no_corr:.6f} МэВ")

# ==============================================================================
# [7] КОНТРОЛЬНЫЕ ASSERTS (audit v5.2, ЧАСТЬ 3 П.4)
# ==============================================================================
assert abs(delta_np_val - 1.28678) < 1e-4, f"ΔM_np = {delta_np_val} вне окна аудита ±1e-4 МэВ"
assert rel_err_Mn < 1e-5, (f"rel_err(M_n) = {rel_err_Mn:.3e} ≥ 1e-5 — "
                           f"запись «0.073%» в таблицах НЕ блокирована")

# ==============================================================================
# [8] ИТОГОВЫЙ ОТВЕТ
# ==============================================================================
print("\n" + "=" * 74)
print(" ИТОГ (v5.2 — формула T(3,2), калибровка точности M_n)")
print("=" * 74)
print(f"   Формула:    ΔM_np = (3/16)·α·M_p·(1 + α/π) ; M_n = M_p + ΔM_np")
print(f"   ΔM_np(ТЭВ)  = {delta_np_val:.8f} МэВ | CODATA {DM_NP_CODATA:.8f} → откл. {dev_rel:+.4f}%")
print(f"   M_n(ТЭВ)    = {M_n_tev:.8f} МэВ | CODATA {M_N_EXP:.8f}")
print(f"   ТОЧНОСТЬ M_n = {ppm_Mn:.2f} ppm (rel_err = {rel_err_Mn:.3e} < 1e-5)")
print("   ВЫВОД: опечатка «0.073%» в Таблицах 2 и 8 манифеста УСТРАНЕНА —")
print(f"   реальная точность {ppm_Mn:.1f} ppm (≈0.00073%), Б1 (×2.52) устранён.")
