import math

def verify_weizsacker_formula():
    print("=== ВЕРИФИКАЦИЯ ФОРМУЛЫ ВАЙЦЗЕККЕРА (SEMF) И ЭНЕРГИИ СВЯЗИ ЯДЕР ===")
    
    # 1. Базовые константы
    E0_MeV = 70.025283
    M_p_MeV = 938.272088
    alpha_inv = 137.035999177
    alpha = 1.0 / alpha_inv
    hbar_c = 197.3269804 # МэВ * фм
    
    # 2. Дедуктивный вывод коэффициентов SEMF
    M_pi = 2.0 * E0_MeV # 140.0505 МэВ
    E_scale = (M_pi**2) / (2.0 * M_p_MeV) # 10.4523 МэВ
    p = 3
    sin2_theta_W = 3.0 / 13.0
    
    # Объемный член: a_v = (3/2) * E_scale
    a_v = 1.5 * E_scale # 15.678 МэВ
    
    # Поверхностный член: a_s = a_v * (1 + 1/2 * sin^2(theta_W)) = a_v * (29/26)
    a_s = a_v * (1.0 + 0.5 * sin2_theta_W) # 17.487 МэВ
    
    # Кулоновский радиус и коэффициент: r_0 ≈ 1.215 фм => a_c = (3/5) * alpha * hbar_c / r_0
    r_0 = 1.215 # фм
    a_c = 0.6 * (alpha * hbar_c) / r_0 # 0.7111 МэВ
    
    # Асимметрия: a_a = (3/2) * a_v
    a_a = 1.5 * a_v # 23.517 МэВ
    
    # Спаривание: a_p = (3/4) * a_v
    a_p = 0.75 * a_v # 11.758 МэВ
    
    print(f"[1] Теоретические коэффициенты формулы Вайцзеккера:")
    print(f"    a_v (Объемный)    = {a_v:.3f} МэВ  (Эксперимент: 15.75 МэВ,  точность {100 - abs(a_v - 15.75)/15.75*100:.2f}%)")
    print(f"    a_s (Поверхность) = {a_s:.3f} МэВ  (Эксперимент: 17.50 МэВ,  точность {100 - abs(a_s - 17.50)/17.50*100:.2f}%)")
    print(f"    a_c (Кулон)       = {a_c:.3f} МэВ  (Эксперимент:  0.711 МэВ, точность {100 - abs(a_c - 0.711)/0.711*100:.2f}%)")
    print(f"    a_a (Асимметрия)  = {a_a:.3f} МэВ  (Эксперимент: 23.60 МэВ,  точность {100 - abs(a_a - 23.60)/23.60*100:.2f}%)")
    print(f"    a_p (Спаривание)  = {a_p:.3f} МэВ  (Эксперимент: 11.70 МэВ,  точность {100 - abs(a_p - 11.70)/11.70*100:.2f}%)")
    
    # 3. Функция расчета энергии связи ядра B(A, Z)
    def calc_binding_energy(A, Z):
        vol = a_v * A
        surf = a_s * (A**(2.0/3.0))
        coul = a_c * Z * (Z - 1.0) / (A**(1.0/3.0))
        asym = a_a * ((A - 2.0 * Z)**2) / A
        
        # Спаривание
        if A % 2 != 0:
            pair = 0.0
        elif Z % 2 == 0:
            pair = +a_p / (A**0.5) # четно-четное
        else:
            pair = -a_p / (A**0.5) # нечетно-нечетное
            
        B = vol - surf - coul - asym + pair
        return B, B / A
    
    # 4. Проверка на ключевых эталонных нуклидах (AME2020)
    nuclei = [
        ("16O (Кислород)", 16, 8, 7.976),
        ("56Fe (Железо - пик стабильности)", 56, 26, 8.790),
        ("208Pb (Свинец - дважды магический)", 208, 82, 7.867),
        ("238U (Уран)", 238, 92, 7.570)
    ]
    
    print(f"\n[2] Расчет удельной энергии связи B/A на эталонных ядрах:")
    for name, A, Z, exp_B_A in nuclei:
        B_total, B_A_theor = calc_binding_energy(A, Z)
        diff = abs(B_A_theor - exp_B_A) / exp_B_A * 100
        print(f"    {name:38s}: B/A = {B_A_theor:.3f} МэВ/нуклон (AME2020: {exp_B_A:.3f} МэВ, точность {100 - diff:.2f}%)")
        
    return True

if __name__ == "__main__":
    verify_weizsacker_formula()
